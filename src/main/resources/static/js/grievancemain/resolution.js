const resolutionUrl = "/grievance/grievance/getResolutionDetails";
function downloadreport(idEnc) {
	$.ajax({
		url: resolutionUrl,
		type: "GET",
		data: {
			idEnc: idEnc,
		},
		success: function(result) {
			if (result.resultObject != null && result.resultObject !== "") {
				var grievancenumber = result.resultObject.applicationNo;
				var type = result.resultObject.grievanceType.type;
				var category = result.resultObject.category.category;
				var subject = result.resultObject.complaint;
				var grievanceDescription = result.resultObject.grievanceDescription;
				var settlementremark = result.resultObject.settlementDescription;
				var incidentplace = result.resultObject.place;
				var incidentDate = '';
				if (result.resultObject.dateOfEventStrDisplay != null) {
					incidentDate = result.resultObject.dateOfEventStrDisplay;
				}
				var status = '';
				if (result.resultObject.status == 'C') {
					status = 'Settled';
				}

				if (result.resultObject.requestType != 'A') {
					var grievantName = result.resultObject.grievantName;
					var mobileNo = result.resultObject.mobileNo;
					var email = result.resultObject.email;
					var address = result.resultObject.address;
				}
				var generatedby = '';
				if (result.userFullName != null) {
					generatedby = result.userFullName;
				}
				var htmlToPrint = `
                
              <div style="text-align: center;">
   				 <table style="border: 1px solid #000; border-collapse: collapse;margin: 20px 72px 0 60px; display: inline-block;">
       				 <tr>
          				  <td style="border: 2px solid #000; padding: 8px;">
              				  <img src="/grievance/images/header.png" style="width: 1000px; max-height: 300px;">
           				 </td>
      				</tr>
   				 </table>
			</div>
			<br>



<div style="text-align: left;" class="row">    
    
    <div class="col-lg-12 d-flex px-0" style="text-align: left;display: flex; width:100%">
    <div class="col-lg-6 px-0" style="width:50%">
    <p style="margin: 20px 0 0 72px; text-align: left;">Grievance Number: ${grievancenumber}<br>
     <p style="margin: 20px 0 0 72px; text-align: left;">Grievant Type: ${type}<br>
     <p style="margin: 20px 0 0 72px; text-align: left;">Grievant Category: ${category}<br>
     <p style="margin: 20px 0 0 72px; text-align: left;">Incident Place: ${incidentplace}<br>
     <p style="margin: 20px 0 0 72px; text-align: left;">Incident Date: ${incidentDate}<br>
      <p style="margin: 20px 0 0 72px; text-align: left;">Status: ${status}<br>
    </div>
    ${result.resultObject.requestType != 'A' ? `
    <div class="col-lg-6 px-0" style="width:50%">
    <p style="margin: 20px 0 0 72px; text-align: left;">Grievant Name: ${grievantName}<br>
     <p style="margin: 20px 0 0 72px; text-align: left;">Mobile No: ${mobileNo}<br>
     <p style="margin: 20px 0 0 72px; text-align: left;">Email: ${email}<br>
     <p style="margin: 20px 0 0 72px; text-align: left;">Address: ${address}<br>
     
    </div>
    ` : ''}
    </div>
    <br>
    
    <div style="display: flex; justify-content: space-between;">
    <div style="margin: 0 72px 0 72px;">
        <p>Subject:${subject}</p>   
    </div>
</div>
<div style="display: flex; justify-content: space-between;">
    <div style="margin: 0 72px 0 72px;">
        <p>Grievance Description:${grievanceDescription}</p>   
    </div>
</div>
    
    <div style="display: flex; justify-content: space-between;">
    <div style="margin: 0 72px 0 72px;">
        <p>Settlement Remark:${settlementremark}</p>   
    </div>
</div>

<div style="display: flex; flex-direction: column; align-items: flex-end; margin: 20px 72px 0 60px;">
    <div>
        <p>Generated By</p> 
    </div>
    <div>
        <p>${generatedby}</p>   
    </div>
</div>
     
    </div>
</div>
`;

				var newWin = window.open("", "(Resolution Report)", "width=1600,height=1600");
				if (newWin != null) {
					newWin.document.write('<html><head></head><body>');
					// Assuming htmlToPrint is defined somewhere in your code
					newWin.document.write(htmlToPrint);
					newWin.document.write('</body></html>');
					newWin.document.close();
					newWin.document.head.insertAdjacentHTML('beforeend', '<style>@page { margin: 0; }</style>');
					newWin.print();
				} else {
					console.error("Failed to open a new window.");
				}
			} else {
				console.error("API response is not valid or empty.");
			}
		},
		error: function(xhr, status, error) {
			console.error("Error fetching data from the API:", error);
		}
	});
}